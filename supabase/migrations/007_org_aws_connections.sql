-- Per-company AWS connection for "bring your own SES": eXomail assumes a role in the customer's account.
-- The backend (service role) is the only reader/writer: RLS is on with no policies, so customers can't
-- change their external ID or point at another account's role from the browser.

CREATE TABLE IF NOT EXISTS public.org_aws_connections (
  org_id        uuid PRIMARY KEY REFERENCES public.organizations(id) ON DELETE CASCADE,
  external_id   text NOT NULL,                 -- generated by eXomail; required by the customer's role trust policy
  role_arn      text,                          -- arn:aws:iam::<account>:role/eXomailSendingRole
  region        text,                          -- SES region, e.g. ap-southeast-2
  config_set    text,                          -- SES configuration set that publishes events to sns_topic_arn
  sns_topic_arn text UNIQUE,                   -- events from this topic only ever touch this company's data
  status        text NOT NULL DEFAULT 'not_connected',  -- not_connected | connected | error
  production_access boolean,
  max_send_rate numeric,
  max_24h_send  numeric,
  last_error    text,
  checked_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.org_aws_connections ENABLE ROW LEVEL SECURITY;
